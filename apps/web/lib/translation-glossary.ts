/**
 * 용어사전 적용 - 정확한 문자열 치환
 * 긴 용어부터 먼저 치환해서 부분 일치 문제 방지
 */
const SORTED_GLOSSARY_KEYS = Object.keys(TRANSLATION_GLOSSARY).sort((a, b) => b.length - a.length);

export function applyGlossary(text: string): string {
  if (!text) return '';
  let result = text;
  for (const key of SORTED_GLOSSARY_KEYS) {
    if (result.includes(key)) {
      result = result.split(key).join(TRANSLATION_GLOSSARY[key]);
    }
  }
  return result;
}

/**
 * 텍스트에 중국어가 포함되어 있는지 확인
 */
export function hasChinese(text: string): boolean {
  return /[\u4e00-\u9fff]/.test(text);
}

/**
 * 중국어 비율 계산 (0~1)
 */
export function chineseRatio(text: string): number {
  if (!text) return 0;
  const chineseChars = text.match(/[\u4e00-\u9fff]/g) || [];
  return chineseChars.length / text.length;
}
